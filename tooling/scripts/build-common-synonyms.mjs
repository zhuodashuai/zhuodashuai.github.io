import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const root=new URL('../../',import.meta.url), check=process.argv.includes('--check');
const file=new URL('tooling/dictionary/chinese-related-common.json',root);
const data=JSON.parse(await fs.readFile(file,'utf8'));
const exampleReview=JSON.parse(await fs.readFile(new URL('tooling/dictionary/chinese-related-common-examples.json',root),'utf8'));
const exampleManifest=JSON.parse(await fs.readFile(new URL('vocab/data/dictionary-examples/manifest-v2.json',root),'utf8'));
const exampleEntries=new Map();
for(const shard of exampleManifest.shards){
 const payload=JSON.parse(await fs.readFile(new URL('vocab/data/dictionary-examples/'+shard.file,root),'utf8'));
 for(const entry of payload.entries)exampleEntries.set(entry.term,entry);
}
assert.equal(exampleReview.schemaVersion,1);
assert.equal(exampleReview.groups.length,data.groups.length);
const aliases=new Set(),ids=new Set();
assert.equal(data.schemaVersion,1);assert.ok(data.groups.length>=150);
const sourceGroups=data.groups.map(r=>{
 assert.ok(['noun','verb','adjective','adverb'].includes(r.pos));
 assert.match(r.sourceId,/^pwn30:\d{8}-[nvar]$/u);
 assert.ok(!ids.has(r.sourceId));ids.add(r.sourceId);
 assert.ok(r.heads.length>=2&&r.heads.length<=6&&r.terms.length>=2);
 assert.ok(r.heads.every(h=>r.sourceMembers.includes(h)));
 for(const term of r.terms){assert.match(term,/^\p{Script=Han}{2,10}$/u);assert.ok(!aliases.has(term),term);aliases.add(term);}
 const scope=exampleReview.groups.find(row=>row.id===r.id);
 assert.ok(scope, r.id+' missing explicit example review');
 assert.deepEqual(Object.keys(scope.heads).sort(),[...r.heads].sort());
 for(const [head,senses] of Object.entries(scope.heads)){
  assert.ok(Array.isArray(senses));
  assert.equal(new Set(senses.map(s=>s.id)).size,senses.length);
  for(const proof of senses){
   assert.deepEqual(Object.keys(proof).sort(),['id','meaningZh','partOfSpeech','examples'].sort());
   assert.deepEqual([...new Set(proof.partOfSpeech.match(/\b(?:noun|verb|adjective|adverb)\b/gu))],[r.pos],head+'/'+proof.id+' wrong or mixed example POS');
   const actual=exampleEntries.get(head)?.senses.find(s=>s.id===proof.id);
   assert.ok(actual,head+'/'+proof.id+' missing example');
   for(const key of ['id','partOfSpeech','meaningZh'])assert.equal(proof[key],actual[key],head+'/'+proof.id+' changed example scope');
   assert.deepEqual(proof.examples,actual.examples,head+'/'+proof.id+' changed example content');
  }
 }
 return {...Object.fromEntries(['id','number','sourceId','pos','sense','terms','heads','note','forbidden','evidence'].map(k=>[k,r[k]])),exampleSenses:scope.heads};
});
const module='// Generated by tooling/scripts/build-common-synonyms.mjs; do not edit by hand.\n'
 +'// Evidence binds one existing source variant and POS to one reviewed sense.\n'
 +'// Relations use Princeton WordNet 3.0 and Chinese Open Wordnet; see data/THIRD_PARTY_NOTICES.md.\n'
 +'export const COMMON_CHINESE_GROUPS = Object.freeze('+JSON.stringify(sourceGroups,null,2)+'.map(group => Object.freeze({ ...group,\n'
 +'  terms: Object.freeze(group.terms), heads: Object.freeze(group.heads), forbidden: Object.freeze(group.forbidden),\n'
 +'  evidence: Object.freeze(group.evidence.map(row => Object.freeze({ ...row, terms: Object.freeze(row.terms) }))),\n'
 +'  exampleSenses: Object.freeze(Object.fromEntries(Object.entries(group.exampleSenses).map(([head, rows]) => [head, Object.freeze(rows.map(row => Object.freeze({ ...row, examples: Object.freeze(row.examples.map(example => Object.freeze(example))) })))]))),\n'
 +'})));\n';
const escape=s=>s.replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;').replaceAll("'",'&#39;');
const pos={noun:'名词',verb:'动词',adjective:'形容词',adverb:'副词'};
const table='<!-- common-synonyms:start -->\n'
 +`      <details id="common-related-catalogue"><summary>常用同义关联表（新增 ${data.groups.length} 组，按词性与义项核对）</summary>\n`
 +'        <table id="common-synonyms-005"><caption>限本行的词性和具体意思；不表示任意语境可替换。只查询本站既有词条，不自动收录，也不调用 AI。</caption>\n'
 +'          <thead><tr><th scope="col">编号</th><th scope="col">中文／词性</th><th scope="col">英文词头与用法范围</th></tr></thead><tbody>\n'
 +data.groups.map(r=>`            <tr data-common-sense="${r.id}"><th scope="row">${r.number}</th><td><a href="dictionary.html#q=${encodeURIComponent(r.terms[0])}">${escape(r.terms[0])}</a>${r.terms.slice(1).map(t=>'／'+escape(t)).join('')}<small>${pos[r.pos]}</small></td><td><span class="related-heads">${escape(r.heads.join(' / '))}</span><small>${escape(r.note)}</small></td></tr>`).join('\n')
 +'\n          </tbody></table>\n'
 +'        <p class="hint">关系来源：<a href="https://wordnet.princeton.edu/">Princeton WordNet 3.0</a> 与 <a href="https://omwn.org/omw1.html">Chinese Open Wordnet</a>。<a href="data/WORDNET-3.0-LICENSE.txt">WordNet 3.0 许可</a> · <a href="data/CHINESE-OPEN-WORDNET-LICENSE.txt">Chinese Open Wordnet 许可</a>。词条释义仍保留各自原始来源。</p>\n'
 +'      </details>\n      <!-- common-synonyms:end -->';
const guideFile=new URL('vocab/guide.html',root),guide=await fs.readFile(guideFile,'utf8');
let outputGuide;
if(guide.includes('<!-- common-synonyms:start -->'))outputGuide=guide.replace(/<!-- common-synonyms:start -->[\s\S]*?<!-- common-synonyms:end -->/u,table);
else outputGuide=guide.replace('      <p><strong>卓的 GitHub 登录与普通账号不同。',`      ${table}\n      <p><strong>卓的 GitHub 登录与普通账号不同。`);
for(const [target,content] of [[new URL('vocab/js/chinese-related-common.js',root),module],[guideFile,outputGuide]]){
 if(check)assert.equal((await fs.readFile(target,'utf8')).replaceAll('\r\n','\n'),content.replaceAll('\r\n','\n'),`${target.pathname} generated drift`);
 else await fs.writeFile(target,content);
}
console.log(JSON.stringify({groups:data.groups.length,aliases:aliases.size,mode:check?'check':'build',moduleBytes:Buffer.byteLength(module)}));
