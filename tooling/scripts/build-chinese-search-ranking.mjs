/** A lossless public reverse-search sidecar; no dictionary source is rewritten. */
import { createHash } from "node:crypto";
import { gzipSync } from "node:zlib";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(import.meta.dirname, "../..");
const sha = bytes => createHash("sha256").update(bytes).digest("hex");
export async function buildChineseSearchRanking({ root = ROOT, check = false } = {}) {
  const sourceRoot = resolve(root, "vocab/data/expanded-dictionary");
  const manifestBytes = await readFile(resolve(sourceRoot, "manifest.json")), manifest = JSON.parse(manifestBytes);
  if (manifest.schemaVersion !== 2 || !/^[a-f0-9]{64}$/u.test(manifest.version)) throw new Error("Invalid dictionary manifest.");
  const canonical = new Map();
  for (const descriptor of manifest.english.shards) {
    const bytes = await readFile(resolve(sourceRoot, descriptor.file));
    if (bytes.length !== descriptor.bytes || sha(bytes) !== descriptor.sha256) throw new Error(`Changed source shard: ${descriptor.file}`);
    const payload = JSON.parse(bytes);
    if (payload.schemaVersion !== 2 || payload.kind !== "en" || payload.bucket !== descriptor.bucket) throw new Error("Invalid English shard.");
    const rows = new Map(payload.records.map(row => [row.id, row]));
    for (const [, refs] of payload.keys) for (const ref of refs) if (ref.kind === "canonical") {
      const row = rows.get(ref.id);
      if (!row) throw new Error("Missing canonical record.");
      const tuples = [row, ...(row.variants || [])].map(item => [item.partOfSpeech, item.source, item.meaning]);
      const projected = [row.id, row.term, tuples], old = canonical.get(row.id);
      if (old && JSON.stringify(old) !== JSON.stringify(projected)) throw new Error("Conflicting canonical source tuple.");
      canonical.set(row.id, projected);
    }
  }
  if (canonical.size !== manifest.counts.records) throw new Error("Canonical dictionary count drift.");
  const payload = { schemaVersion: 1, dictionaryVersion: manifest.version, records: [...canonical.values()].sort((a, b) => a[0] - b[0]) };
  const uncompressed = Buffer.from(`${JSON.stringify(payload)}\n`), compressed = gzipSync(uncompressed, { level: 9 });
  // RFC 1952 permits 255 (unknown) for OS. Keep this metadata independent of
  // the build host so Windows and Linux produce the same hashed artifact.
  compressed[9] = 255;
  // A .bin representation avoids HTTP servers treating the file suffix as a
  // Content-Encoding instruction and transparently decoding our hashed body.
  const digest = sha(compressed), filename = `${digest}.bin`;
  const release = { schemaVersion: 1, dictionaryVersion: manifest.version, sourceManifestSha256: sha(manifestBytes),
    records: canonical.size, file: `${manifest.version}/${filename}`, sha256: digest,
    bytes: compressed.length, uncompressedBytes: uncompressed.length };
  const releaseText = `// Generated by tooling/scripts/build-chinese-search-ranking.mjs.\nexport const CHINESE_RANKING_RELEASE = Object.freeze(${JSON.stringify(release, null, 2)});\n`;
  const directory = resolve(root, "vocab/data/chinese-search-ranking", manifest.version);
  const dataFile = resolve(directory, filename), releaseFile = resolve(root, "vocab/js/chinese-ranking-release.js");
  if (check) {
    if (!(await readFile(dataFile)).equals(compressed) || await readFile(releaseFile, "utf8") !== releaseText) throw new Error("Stale Chinese ranking sidecar; run its builder.");
  } else {
    await mkdir(directory, { recursive: true }); await writeFile(dataFile, compressed); await writeFile(releaseFile, releaseText);
  }
  return release;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(JSON.stringify(await buildChineseSearchRanking({ check: process.argv.includes("--check") })));
}
