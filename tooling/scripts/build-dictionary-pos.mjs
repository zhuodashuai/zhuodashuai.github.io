/** Deterministic, no-network POS-only projection for the compact core lookup. */
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseCoreDictionary } from "../../vocab/js/core-dictionary.js";
import { personalDictionaryResult } from "../../vocab/js/personal-dictionary.js";
import { DICTIONARY_POS_SOURCE, verifyDictionaryPos } from "../lib/dictionary-pos.mjs";

const ROOT = resolve(import.meta.dirname, "../..");
const digest = value => createHash("sha256").update(value).digest("hex");
const compare = (a, b) => a < b ? -1 : a > b ? 1 : 0;

/** Build only from independently approved labels and exactly matching current raw core glosses. */
export function buildCorePosCorrections(corePayload, pack, integrity) {
  verifyDictionaryPos(pack, integrity);
  const core = parseCoreDictionary(corePayload);
  if (core.source.name !== "ECDICT" || core.source.license !== "MIT"
    || !/^https:\/\/github\.com\/skywind3000\/ECDICT\/?$/u.test(core.source.url)) throw new Error("Invalid compact POS core provenance.");
  const reviews = new Map(pack.entries.filter(entry => entry.baseSource === "core").map(entry => [entry.term, entry]));
  const entries = [];
  for (const row of core.entries.values()) {
    const displayed = personalDictionaryResult(row);
    if (!displayed || row.partOfSpeech.trim() || displayed.partOfSpeech.trim()) continue;
    const review = reviews.get(row.word);
    if (!review || review.meaningSha256 !== digest(row.meaning)) continue;
    entries.push([row.word, row.meaning, review.partOfSpeech]);
  }
  entries.sort(([a], [b]) => compare(a, b));
  return { schemaVersion: 1, source: { ...DICTIONARY_POS_SOURCE }, root: { ...integrity },
    coreSemanticSha256: digest(JSON.stringify(corePayload)), entries };
}

export function renderCorePosCorrections(projection) {
  return `// Generated by tooling/scripts/build-dictionary-pos.mjs; do not edit by hand.\n// POS are word-level labels; exact original meanings and source credit remain separate.\nexport const CORE_POS_CORRECTIONS = Object.freeze({\n  schemaVersion: 1,\n  source: Object.freeze(${JSON.stringify(projection.source)}),\n  root: Object.freeze(${JSON.stringify(projection.root)}),\n  coreSemanticSha256: ${JSON.stringify(projection.coreSemanticSha256)},\n  entries: Object.freeze([${projection.entries.map(row => `\n    Object.freeze(${JSON.stringify(row)})`).join(",")}\n  ])\n});\n`;
}

export async function generateDictionaryPos({ root = ROOT, check = false } = {}) {
  const [coreBytes, packBytes, integrityBytes] = await Promise.all([
    readFile(resolve(root, "vocab/data/ecdict-core.json"), "utf8"),
    readFile(resolve(root, "tooling/dictionary/pos/pos-completion-2026-10-19.json"), "utf8"),
    readFile(resolve(root, "tooling/dictionary/pos/integrity.json"), "utf8")
  ]);
  const projection = buildCorePosCorrections(JSON.parse(coreBytes), JSON.parse(packBytes), JSON.parse(integrityBytes));
  const output = renderCorePosCorrections(projection);
  const path = resolve(root, "vocab/js/core-pos-corrections.js");
  if (check) {
    if (await readFile(path, "utf8") !== output) throw new Error("Compact POS correction module is stale; run node tooling/scripts/build-dictionary-pos.mjs.");
  } else await writeFile(path, output);
  return { rows: projection.entries.length, bytes: Buffer.byteLength(output), sha256: digest(output),
    coreSemanticSha256: projection.coreSemanticSha256, integrity: projection.root };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { console.log(JSON.stringify(await generateDictionaryPos({ check: process.argv.includes("--check") }), null, 2)); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
